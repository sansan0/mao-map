import { mkdir, readFile, writeFile, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

// Use the upstream SVG files unchanged apart from decorative accessibility attrs
// and the shared sizing class. The generated subset also works on GitHub Pages.
const root = fileURLToPath(new URL('../', import.meta.url));
const source = path.join(root, 'node_modules/lucide-static');
const output = path.join(root, 'libs/lucide');
const { version } = JSON.parse(await readFile(path.join(source, 'package.json'), 'utf8'));
const names = [
  'arrow-right', 'arrow-up-right', 'book-open', 'check', 'chevron-down',
  'chevron-right', 'chevron-up', 'circle-help', 'copy', 'crosshair', 'list',
  'loader-circle', 'map', 'map-pin', 'maximize', 'minus', 'music', 'pause', 'play',
  'plus', 'rotate-ccw', 'route', 'search', 'skip-back', 'skip-forward',
  'sliders-horizontal', 'square', 'x',
];
const icons = {};
for (const name of names) {
  const svg = await readFile(path.join(source, 'icons', `${name}.svg`), 'utf8');
  icons[name] = svg.replace(/<!--[\s\S]*?-->/g, '').trim()
    .replace(/\s+/g, ' ')
    .replace('class="lucide ', 'class="icon lucide ')
    .replace('<svg ', `<svg data-lucide="${name}" aria-hidden="true" focusable="false" `);
}
await mkdir(output, { recursive: true });
await writeFile(path.join(output, 'icons.js'), `/* Generated by npm run icons:sync from lucide-static v${version}.
 * Official icons: https://lucide.dev — full licenses in ./LICENSE. */
(() => {
  'use strict';
  const icons = Object.freeze(${JSON.stringify(icons, null, 2)});
  window.JourneyIcons = Object.freeze({
    svg(name) {
      if (!Object.prototype.hasOwnProperty.call(icons, name)) throw new Error('Unknown Lucide icon: ' + name);
      return icons[name];
    },
  });
})();
`, 'utf8');
// Native disclosure markers use the same upstream icon through a CSS mask.
await copyFile(path.join(source, 'icons/chevron-right.svg'), path.join(output, 'chevron-right.svg'));
await copyFile(path.join(source, 'LICENSE'), path.join(output, 'LICENSE'));
console.log(`Synced ${names.length} Lucide ${version} icons to libs/lucide.`);
